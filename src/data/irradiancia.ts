// Helper: get monthly irradiance array for a city (returns annual average if not found)
export function getMonthlyIrradiance(cidade: string, uf: string): number[] | null {
  const normalized = cidade.toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  const entry = irradianciaBrasil.find(c => {
    const cNorm = c[0].normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    return cNorm === normalized && c[1] === uf;
  });
  if (entry) return entry.slice(2) as number[];

  // Try partial match
  const partial = irradianciaBrasil.find(c => {
    const cNorm = c[0].normalize('NFD').replace(/[\u0300-\u036f]/g, '');
    return cNorm.includes(normalized) || normalized.includes(cNorm);
  });
  if (partial) return partial.slice(2) as number[];

  return null;
}

export function getDefaultIrradiance(): number[] {
  const tl = irradianciaBrasil.find(c => c[0] === CIDADE_PADRAO && c[1] === UF_PADRAO);
  return tl ? (tl.slice(2) as number[]) : [5.0,5.0,5.0,5.0,5.0,5.0,5.0,5.0,5.0,5.0,5.0,5.0];
}

export function getAverageIrradiance(monthly: number[]): number {
  return monthly.reduce((a, b) => a + b, 0) / 12;
}

// Search cities for autocomplete
export function searchCidades(query: string): { cidade: string; uf: string }[] {
  if (!query || query.length < 2) return [];
  const normalized = query.toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  return irradianciaBrasil
    .filter(c => {
      const cNorm = c[0].normalize('NFD').replace(/[\u0300-\u036f]/g, '');
      return cNorm.includes(normalized);
    })
    .slice(0, 10)
    .map(c => ({ cidade: c[0], uf: c[1] }));
}
